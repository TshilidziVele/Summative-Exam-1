 private void processSale() {
    try {
        String customerName = txtCustomerName.getText().trim();
        String productName = cmbProduct.getSelectedItem().toString();
        double price = Double.parseDouble(txtPrice.getText().trim());

        if (customerName.isEmpty() || price <= 0) {
            JOptionPane.showMessageDialog(this, "Enter a customer name and a price above zero.");
            return;
        }
        IProductCalculations calc = new ProductCalculations(price);

        String details = "Customer Name: " + customerName
                + "\nProduct: " + productName
                + "\nVAT: R " + calc.GetVat()
                + "\nCOMMISSION: R " + calc.GetCommission()
                + "\nTOTAL: R " + calc.GetTotal();

        JOptionPane.showMessageDialog(this, details);  
        saveToFile(details);                        
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this, "Please enter a valid numeric price.");
    }
}
private void saveToFile(String details) {
    String stars = "*".repeat(34);
    try (PrintWriter out = new PrintWriter(new FileWriter("data.txt"))) {
        out.println("DATA LOG");
        out.println(stars);
        out.println(details);
        out.println(stars);
    } catch (IOException ex) {
        JOptionPane.showMessageDialog(this, "Error saving file: " + ex.getMessage());
    }
}
private void clearForm() {
    txtCustomerName.setText("");
    txtPrice.setText("");
    cmbProduct.setSelectedIndex(0);
}
